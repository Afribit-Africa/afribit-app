/** What a feature needs from the network, in the shell's own words (M01/J-05). */
export function networkNeedLabel(network: NetworkRequirement, l: Locale): string {
  const t = strings[l];
  switch (network) {
    case 'none': return t.networkWorksOffline;
    case 'internet': return t.networkNeedsInternet;
    case 'mesh': return t.networkWorksOnMesh;
    case 'internet-or-mesh': return t.networkNeedsInternetOrMesh;
  }
}

export function availabilityLabel(a: AvailabilityResult, l: Locale): { label: string; tone: 'positive' | 'neutral' | 'warning' | 'accent' } | undefined {
  if (a.status === 'available') return undefined;
  const label = reasonText[l][a.reason];
  if (a.reason === 'preview') return { label, tone: 'accent' };
  if (a.status === 'limited') return { label, tone: 'warning' };
  return { label, tone: 'neutral' };
}
